# S34: Inside Day Breakout
# An inside day = today's range is entirely within yesterday's range.
# This signals low volatility compression. The next big move often
# follows. Go long if the compression resolves upward (above yesterday high).
# This is an intraday concept approximated with daily data.
df["prev_high"] = df["Price"].shift(1) * 1.002  # approximate: +0.2%
df["prev_low"]  = df["Price"].shift(1) * 0.998  # approximate: -0.2%
# Inside day: today's move is small relative to prior day
df["daily_range"] = df["Price"].pct_change().abs()
df["is_inside"]   = df["daily_range"] < df["daily_range"].shift(1) * 0.5

inside_pos = 0; inside_sig = []
for i in range(len(df)):
    if df["is_inside"].iloc[i] and i > 0:
        # compression day: direction resolved next day by price action
        inside_pos = 1 if df["ret"].iloc[i] > 0 else -1
    inside_sig.append(inside_pos)

s34 = pd.Series(inside_sig, index=df.index, dtype=float)
register(run_strategy(s34, returns, "S34: Inside Day Breakout"))

