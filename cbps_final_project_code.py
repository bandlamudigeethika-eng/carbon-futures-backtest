# S32: Donchian Channel Breakout (20-day)
# Buy when price makes a 20-day high (strongest short-term breakout).
# Sell when price makes a 20-day low.
# Classic turtle trading rule, widely used in commodity futures.
df["don20_high"] = df["Price"].shift(1).rolling(20).max()  # yesterday's 20d high
df["don20_low"]  = df["Price"].shift(1).rolling(20).min()  # yesterday's 20d low
