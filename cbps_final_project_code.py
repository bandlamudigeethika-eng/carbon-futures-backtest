"""Mean-reversion family
This family tests the opposite idea: prices sometimes move too far and then come back. Mean reversion means the price may return toward its average after an extreme move.This can happen when news causes short-term overreaction.
These strategies are important in carbon markets because regulation and energy shocks can push prices away from fair value for a while.
In simple terms, they are trying to buy when the market has fallen too much and sell when it has risen too much.
"""

# ================================================================
# CELL 7 - MEAN REVERSION FAMILY (S9-S15)
# ================================================================
# Carbon prices occasionally overshoot when news hits: energy
# shocks, ETS reform votes, political surprises. Without a
# fundamental anchor (no earnings, no cashflow), the overshoot
# can be severe and the snap-back equally sharp. Mean reversion
# strategies try to capture that snap-back.
# ================================================================

print("\nFAMILY 2 - MEAN REVERSION")

# S9: RSI 14-day
# RSI below 35 = oversold, momentum has exhausted downward.
# RSI above 65 = overbought, momentum has exhausted upward.
# Thresholds are wider than the standard 30/70 because carbon
# spends more time in extreme readings than equities do.
df["rsi14"] = rsi(df["Price"], 14)
s9 = pd.Series(
    np.where(df["rsi14"] < 35, 1.0,
    np.where(df["rsi14"] > 65, -1.0, 0.0)),
    index=df.index)
register(run_strategy(s9, returns, "S09: RSI 14 Mean Reversion"))

# S10: RSI 7-day (faster)
# Shorter RSI reacts to sharper intraday moves and post-auction
# price dislocations. Tests whether carbon has a shorter reversion cycle.
df["rsi7"] = rsi(df["Price"], 7)
s10 = pd.Series(
    np.where(df["rsi7"] < 30, 1.0,
    np.where(df["rsi7"] > 70, -1.0, 0.0)),
    index=df.index)
register(run_strategy(s10, returns, "S10: RSI 7 Fast Mean Reversion"))

# S11: Bollinger Band Fade
# Price > upper band = overbought, fade the move (go short).
# Price < lower band = oversold, buy the dip (go long).
# Tests whether carbon extreme moves reverse to the 20-day mean.
df["bb_mid"]   = df["Price"].rolling(20).mean()
df["bb_std"]   = df["Price"].rolling(20).std()
df["bb_upper"] = df["bb_mid"] + 2 * df["bb_std"]
df["bb_lower"] = df["bb_mid"] - 2 * df["bb_std"]
s11 = pd.Series(
    np.where(df["Price"] < df["bb_lower"],  1.0,
    np.where(df["Price"] > df["bb_upper"], -1.0, 0.0)),
    index=df.index)
register(run_strategy(s11, returns, "S11: Bollinger Band Fade"))

# S12: Bollinger Breakout (opposite of S11)
# Go WITH the breakout rather than against it.
# Stateful: hold the position until price crosses back through midline.
# Directly tests whether carbon moves are trending or mean-reverting
# at the extremes. Comparing S11 vs S12 gives a definitive answer.
bb_pos = 0; bb_sig = []
for i in range(len(df)):
    p, u, l, m = (df["Price"].iloc[i], df["bb_upper"].iloc[i],
                  df["bb_lower"].iloc[i], df["bb_mid"].iloc[i])
    if np.isnan(u):
        bb_sig.append(0); continue
    if p > u:                          bb_pos = 1
    elif p < l:                        bb_pos = -1
    elif bb_pos == 1  and p < m:       bb_pos = 0
    elif bb_pos == -1 and p > m:       bb_pos = 0
    bb_sig.append(bb_pos)
s12 = pd.Series(bb_sig, index=df.index, dtype=float)
register(run_strategy(s12, returns, "S12: Bollinger Breakout Stateful"))

# S13: Z-Score 60-Day Mean Reversion
# How many standard deviations is price from its 60-day mean?
# Entry at +/- 1.5 sigma balances signal frequency vs significance.
# Purely statistical: no RSI formula, no band arithmetic.
df["zmean60"] = df["Price"].rolling(60).mean()
df["zstd60"]  = df["Price"].rolling(60).std()
df["zscore"]  = (df["Price"] - df["zmean60"]) / df["zstd60"]
s13 = pd.Series(
    np.where(df["zscore"] < -1.5,  1.0,
    np.where(df["zscore"] >  1.5, -1.0, 0.0)),
    index=df.index)
register(run_strategy(s13, returns, "S13: Z-Score 60d Mean Reversion"))

# S14: Z-Score 120-Day (Longer Memory)
# Same logic as S13 but uses a 120-day mean.
# Tests whether carbon has a quarterly or semi-annual mean.
df["zmean120"] = df["Price"].rolling(120).mean()
df["zstd120"]  = df["Price"].rolling(120).std()
df["zscore120"] = (df["Price"] - df["zmean120"]) / df["zstd120"]
s14 = pd.Series(
    np.where(df["zscore120"] < -1.5,  1.0,
    np.where(df["zscore120"] >  1.5, -1.0, 0.0)),
    index=df.index)
register(run_strategy(s14, returns, "S14: Z-Score 120d Mean Reversion"))

# S15: Distance from 52-Week High
# Buy when price has fallen more than 15% from its 52-week high.
# This is a contrarian value signal: price is deeply discounted
# vs. recent highs, suggesting over-reaction to negative news.
df["high_52w"] = df["Price"].rolling(252).max()
df["dist_52w"] = df["Price"] / df["high_52w"] - 1  # negative when below high
s15 = pd.Series(
    np.where(df["dist_52w"] < -0.15, 1.0, 0.0),  # 15% below high = buy
    index=df.index)
register(run_strategy(s15, returns, "S15: Buy 15pct Below 52W High"))

# Chart: all mean reversion indicators
fig, axes = plt.subplots(3, 1, figsize=(16, 12), sharex=True)

axes[0].plot(df["Price"],    color="#aaa",    lw=0.9, alpha=0.7, label="Price")
axes[0].plot(df["bb_mid"],   color="#3498db", lw=1.2, label="BB Mid (20d)")
axes[0].plot(df["bb_upper"], color="#e74c3c", lw=1.0, label="+2 sigma")
axes[0].plot(df["bb_lower"], color="#2ecc71", lw=1.0, label="-2 sigma")
axes[0].fill_between(df.index, df["bb_upper"], df["bb_lower"],
                     alpha=0.05, color="white")
axes[0].set_title("Bollinger Bands - S11 Fades, S12 Follows Breakout",
                  fontweight="bold")
axes[0].set_ylabel("EUR/tonne"); axes[0].legend(fontsize=9)

axes[1].plot(df["rsi14"], color="#9b59b6", lw=1.2, label="RSI 14")
axes[1].plot(df["rsi7"],  color="#3498db", lw=1.0, label="RSI 7", alpha=0.7)
axes[1].axhline(70, color="#e74c3c", lw=1)
axes[1].axhline(65, color="#e74c3c", lw=0.8, alpha=0.5)
axes[1].axhline(35, color="#2ecc71", lw=0.8, alpha=0.5)
axes[1].axhline(30, color="#2ecc71", lw=1)
axes[1].axhline(50, color="white",   lw=0.5, alpha=0.4)
axes[1].fill_between(df.index, df["rsi14"], 35,
                     where=(df["rsi14"] < 35), alpha=0.25, color="#2ecc71")
axes[1].fill_between(df.index, df["rsi14"], 65,
                     where=(df["rsi14"] > 65), alpha=0.25, color="#e74c3c")
axes[1].set_title("RSI Indicators - S09 (14d) and S10 (7d)", fontweight="bold")
axes[1].set_ylabel("RSI"); axes[1].set_ylim(0, 100); axes[1].legend(fontsize=9)

axes[2].plot(df["zscore"],   color="#1abc9c", lw=1.2, label="Z-Score 60d")
axes[2].plot(df["zscore120"], color="#f39c12", lw=1.0, label="Z-Score 120d", alpha=0.8)
axes[2].axhline( 1.5, color="#e74c3c", lw=1)
axes[2].axhline(-1.5, color="#2ecc71", lw=1)
axes[2].axhline( 0,   color="white",   lw=0.5, alpha=0.4)
axes[2].fill_between(df.index, df["zscore"], -1.5,
                     where=(df["zscore"] < -1.5), alpha=0.2, color="#2ecc71")
axes[2].fill_between(df.index, df["zscore"],  1.5,
                     where=(df["zscore"] >  1.5), alpha=0.2, color="#e74c3c")
axes[2].set_title("Z-Score vs 60d and 120d Mean - S13 and S14", fontweight="bold")
