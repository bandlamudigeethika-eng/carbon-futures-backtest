"""This part creates one shared function called run_strategy that can test any trading idea. A signal series tells the function when to be invested and when to stay out of the market. The function then calculates strategy returns, cumulative growth, volatility, drawdown, Sharpe ratio, and other performance metrics. It also includes transaction costs, which matters because real trading is never free.
The function also stores results in a list and keeps equity curves for later comparison. That makes it easy to build tables and charts at the end. A benchmark buy-and-hold strategy is used as the comparison point. This matters because a strategy is only useful if it does better than just holding the market.

"""

# ================================================================
# CELL 5 - STRATEGY ENGINE (shared evaluation function)
# ================================================================

results       = []         # collects metric dicts for all strategies
equity_curves = {}         # stores daily return series for all strategies
returns       = df["ret"]  # convenience reference

def run_strategy(signal, returns, name, cost_bps=2):
    """
    Evaluates any strategy given a position signal series.

    Arguments:
        signal    : pd.Series with values in {-1, 0, 1}
                    -1 = short, 0 = flat, 1 = long
        returns   : pd.Series of daily log returns
        name      : string label shown in all charts and tables
        cost_bps  : one-way transaction cost in basis points
                    2bp is conservative for carbon futures
                    (liquid equity index = 0.5bp, carbon = wider spread)

    The signal is shifted by 1 day before multiplying with returns.
    This is the most important implementation detail: it ensures
    we only act on information available at end of day t-1,
    never on day t's return. Without this shift the backtest
    would have look-ahead bias and be completely invalid.
    """
    pos      = signal.shift(1).fillna(0)               # no look-ahead
    turnover = pos.diff().abs().fillna(0)               # 1 when position changes
    cost     = turnover * (cost_bps / 10000)            # cost in decimal
    strat_ret = (pos * returns - cost).dropna()         # net P&L

    if len(strat_ret) < 60:                             # need enough data
        return None

    total_ret  = np.exp(strat_ret.cumsum()).iloc[-1] - 1
    ann_ret    = strat_ret.mean() * 252
    ann_vol    = strat_ret.std() * np.sqrt(252)
    sharpe     = ann_ret / ann_vol if ann_vol > 0 else 0

    # Sortino uses only downside deviation in the denominator
    # Better than Sharpe when return distributions are asymmetric
    down_vol   = strat_ret[strat_ret < 0].std() * np.sqrt(252)
    sortino    = ann_ret / down_vol if down_vol > 0 else 0

    # Maximum drawdown: largest % decline from any peak
    wealth     = np.exp(strat_ret.cumsum())
    max_dd     = ((wealth - wealth.cummax()) / wealth.cummax()).min()

    # Calmar = annualised return divided by absolute max drawdown
    # Higher Calmar = more return per unit of worst-case pain
    calmar     = ann_ret / abs(max_dd) if max_dd != 0 else 0

    # Win rate = fraction of active (non-zero position) days with positive P&L
    active     = strat_ret[pos.reindex(strat_ret.index) != 0]
    win_rate   = (active > 0).mean() if len(active) > 0 else 0

    # Average hold = total days divided by number of position changes
    changes    = (pos != pos.shift(1)).sum()
    avg_hold   = len(pos) / max(changes, 1)

    return {
        "Strategy"        : name,
        "Total Ret (%)"   : round(total_ret * 100, 1),
        "Ann. Ret (%)"    : round(ann_ret * 100, 2),
        "Ann. Vol (%)"    : round(ann_vol * 100, 2),
        "Sharpe"          : round(sharpe, 3),
        "Sortino"         : round(sortino, 3),
        "Calmar"          : round(calmar, 3),
        "Max DD (%)"      : round(max_dd * 100, 1),
        "Win Rate (%)"    : round(win_rate * 100, 1),
        "Avg Hold (days)" : round(avg_hold, 1),
        "_ret"            : strat_ret,
    }

def register(r):
    #Adds a completed strategy to the results list and equity_curves dict
    if r is None:
        return
    equity_curves[r["Strategy"]] = r["_ret"]
    results.append({k: v for k, v in r.items() if k != "_ret"})
    print(f"  {r['Strategy']:<42}  Sharpe {r['Sharpe']:+.3f}"
          f"  AnnRet {r['Ann. Ret (%)']:+5.1f}%"
          f"  MaxDD {r['Max DD (%)']:5.1f}%")

    # Helper: calculate RSI for any window
def rsi(series, window=14):
    delta = series.diff()
    gain  = delta.clip(lower=0).rolling(window).mean()
    loss  = (-delta.clip(upper=0)).rolling(window).mean()
    rs    = gain / loss
    return 100 - (100 / (1 + rs))

# Helper: Keltner Channel (ATR-based volatility band)
def atr(high, low, close, window=14):
    tr = pd.concat([
        high - low,
        (high - close.shift(1)).abs(),
        (low  - close.shift(1)).abs(),
    ], axis=1).max(axis=1)
    return tr.rolling(window).mean()


