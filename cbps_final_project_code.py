# S2: SMA 50/200 Golden Cross
# Institutional signal. Much slower, captures multi-month cycles.
# 200-day MA represents approximately 10 months of price memory.
df["sma200"] = df["Price"].rolling(200).mean()
s2 = pd.Series(np.where(df["sma50"] > df["sma200"], 1.0, 0.0), index=df.index)
register(run_strategy(s2, returns, "S02: SMA 50/200 Golden Cross"))

# S3: EMA 12/26 Crossover
# Exponential MA weights recent prices more heavily than simple MA.
# Reacts faster to trend changes, fewer false signals in trending markets.
df["ema12"] = df["Price"].ewm(span=12, adjust=False).mean()
df["ema26"] = df["Price"].ewm(span=26, adjust=False).mean()
s3 = pd.Series(np.where(df["ema12"] > df["ema26"], 1.0, 0.0), index=df.index)
register(run_strategy(s3, returns, "S03: EMA 12/26 Crossover"))

# S4: Triple EMA Stack
# All three EMAs must be in order: fast > medium > slow.
# A stricter trend filter that reduces false signals in choppy markets.
# Only go long when short, medium and long term all agree.
df["ema9"]  = df["Price"].ewm(span=9,  adjust=False).mean()
df["ema21"] = df["Price"].ewm(span=21, adjust=False).mean()
df["ema55"] = df["Price"].ewm(span=55, adjust=False).mean()
s4_cond = (df["ema9"] > df["ema21"]) & (df["ema21"] > df["ema55"])
s4 = pd.Series(np.where(s4_cond, 1.0, 0.0), index=df.index)
register(run_strategy(s4, returns, "S04: Triple EMA Stack (9/21/55)"))

# S5: MACD Long/Short
# MACD line = EMA12 minus EMA26 (measures the gap between them).
# Signal line = 9-day EMA of MACD.
# Long when MACD crosses above signal, short below.
# Unlike S3, this takes short positions, not just flat.
df["macd"]        = df["ema12"] - df["ema26"]
df["macd_sig"]    = df["macd"].ewm(span=9, adjust=False).mean()
s5 = pd.Series(np.where(df["macd"] > df["macd_sig"], 1.0, -1.0), index=df.index)
register(run_strategy(s5, returns, "S05: MACD Long/Short"))

# S6: Parabolic SAR Approximation
# SAR (Stop and Reverse) places a trailing stop that accelerates
# as the trend continues. Simple approximation: long if price >
# 20-day high minus 2 ATR, short if below 20-day low plus 2 ATR.
df["high_approx"] = df["Price"].rolling(20).max()
df["low_approx"]  = df["Price"].rolling(20).min()
df["atr14"]       = atr(df["Price"]*1.002, df["Price"]*0.998, df["Price"], 14)
sar_long  = df["Price"] > (df["high_approx"] - 2 * df["atr14"])
sar_short = df["Price"] < (df["low_approx"]  + 2 * df["atr14"])
s6 = pd.Series(np.where(sar_long, 1.0, np.where(sar_short, -1.0, 0.0)),
               index=df.index)
register(run_strategy(s6, returns, "S06: Parabolic SAR Approx"))

# S7: 12-Month Momentum (Skip-1)
# Classic commodity momentum: return over past 12 months excluding
# the most recent month. The skip avoids the short-term reversal
# bias documented in academic literature across commodity markets.
# 252 trading days = 12 months, 21 = 1 month skip.
df["mom_12_1"] = df["Price"].shift(21) / df["Price"].shift(252) - 1
s7 = pd.Series(np.where(df["mom_12_1"] > 0, 1.0, 0.0), index=df.index)
